#!/usr/bin/env node
/**
 * Copy the shared design-token rules and the generated token table out to the
 * sibling module repositories.
 *
 *   node scripts/vendor-lint.mjs [path-to-module …]     (npm run vendor:lint)
 *
 *   node scripts/vendor-lint.mjs --check                (CI's contract-drift job)
 *
 * Defaults to ../DREVisualizations, ../DRESearch and ../DRE-LinkedData, which
 * is how the four repos are checked out side by side (scripts/lib/siblings.mjs
 * resolves them; CI's `../DRE-Search` alias is accepted too).
 *
 * A module that is not checked out is reported as MISSING, never as current,
 * and `--check` fails on it: a check that cannot see a copy cannot vouch for
 * it. Until 2.48 the default looked for ../DRE-Search, which no local checkout
 * is called, so `--check` skipped DRE Search with a warning and exited 0.
 *
 * WHY VENDOR RATHER THAN DEPEND. The modules are separate repositories on their
 * own release cadence, installed into an Omeka site independently of the theme;
 * a build-time dependency on the theme would be a lie about how they ship. So
 * the rules are COPIED, with a header saying where they came from, and each
 * module's lint fails loudly if its copy has been edited in place: alongside
 * the copies this writes scripts/lib/VENDORED.sha256, and each module's
 * check-design-tokens.mjs refuses to run when a copy no longer matches it.
 *
 * What this replaces: three hand-written lint scripts, two of which opened by
 * claiming they mirrored the theme's and neither of which did.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createHash } from 'node:crypto';

import { sibling } from './lib/siblings.mjs';

const ROOT = join(import.meta.dirname, '..');
const DEFAULT_TARGETS = ['visualizations', 'search', 'linkedData'].map((key) => sibling(key, ROOT).path);

const targets = process.argv.slice(2).filter((a) => !a.startsWith('-'));
const check = process.argv.includes('--check');
const list = targets.length ? targets.map((t) => resolve(ROOT, t)) : DEFAULT_TARGETS;

const BANNER = `/**
 * VENDORED from DRE-theme — do not edit here.
 *
 * Source of truth: DRE-theme/scripts/lib/token-rules.mjs
 * Refresh with:    (in DRE-theme) npm run vendor:lint
 *
 * The design-token rules are shared across DRE-theme, DRE-Visualizations,
 * DRESearch and DRE-LinkedData so they cannot drift apart again. Repo-specific
 * paths and allowlists belong in this repo's scripts/check-design-tokens.mjs,
 * not here.
 */
`;

const artefacts = [
  {
    from: join(ROOT, 'scripts', 'lib', 'token-rules.mjs'),
    to: ['scripts', 'lib', 'token-rules.mjs'],
    banner: BANNER,
  },
  {
    from: join(ROOT, 'asset', 'css', 'dre-tokens-fallback.json'),
    to: ['scripts', 'lib', 'dre-tokens-fallback.json'],
    banner: '',
  },
];

const sha256 = (text) => createHash('sha256').update(text, 'utf8').digest('hex');

// What each module receives: the artefacts, then a manifest of their hashes.
const files = artefacts.map(({ from, to, banner }) => ({
  to,
  content: banner + readFileSync(from, 'utf8'),
}));
files.push({
  to: ['scripts', 'lib', 'VENDORED.sha256'],
  content: [
    '# GENERATED by DRE-theme `npm run vendor:lint` — do not edit.',
    '# sha256 of each vendored file; check-design-tokens.mjs verifies them.',
    ...files.map(({ to, content }) => `${sha256(content)}  ${to.join('/')}`),
  ].join('\n') + '\n',
});

let stale = 0;
const missing = [];
for (const target of list) {
  if (!existsSync(target)) {
    console.warn(`  MISSING (not checked out): ${target}`);
    missing.push(target);
    continue;
  }
  let targetStale = 0;
  for (const { to, content } of files) {
    const dest = join(target, ...to);
    const current = existsSync(dest) ? readFileSync(dest, 'utf8') : null;
    if (current === content) continue;
    if (check) {
      console.error(`  STALE: ${join(target, ...to)}`);
      stale++;
      targetStale++;
      continue;
    }
    mkdirSync(join(target, ...to.slice(0, -1)), { recursive: true });
    writeFileSync(dest, content);
    console.log(`  wrote ${join(target, ...to)}`);
  }
  if (check && !targetStale) console.log(`  current: ${target}`);
}

if (check && stale) {
  console.error(`\n${stale} vendored artefact(s) out of date. Run \`npm run vendor:lint\`.`);
}
if (missing.length) {
  console.error(`\n${missing.length} module checkout(s) missing, so ${check ? 'not checked' : 'not written'}.`
    + ' Check them out beside this repository.');
}
if (check && (stale || missing.length)) process.exit(1);
if (!check) console.log(`Vendored lint rules + token table into ${list.length - missing.length} of ${list.length} module(s).`);
