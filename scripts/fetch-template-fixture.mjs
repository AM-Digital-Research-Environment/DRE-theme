#!/usr/bin/env node
/**
 * Refresh tests/fixtures/research-items-template.json from the live AMIRA API.
 *
 *   node scripts/fetch-template-fixture.mjs      (also: npm run fixtures:refresh)
 *
 * The fixture is the ground truth the metadata-grouping check runs against: the
 * full property list of the "Research Items" resource template, plus the terms
 * actually present on a representative record. It is COMMITTED so the check
 * works offline and in CI, and refreshed deliberately when the template changes.
 *
 * Why a fixture and not a hard-coded list in the check: the grouping map in
 * helper/ResourceGroups.php was first written from the field names visible in
 * the MongoDB2OmekaS mapper source, and that was wrong in a way no amount of
 * re-reading the mapper would have revealed — the template carries 54
 * `marcrel:*` contributor roles that the mapper generates rather than spells
 * out, so `marcrel:aut` (the Author) was not in the map and would have rendered
 * under "Further details". Only the real template says what a record contains.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const API = process.env.DRE_API ?? 'https://data.africamultiple.uni-bayreuth.de/api';
const TEMPLATE_ID = 10; // Research Items
const SAMPLE_ITEM_ID = 32324; // the journal article AUDIT.md reviews
const OUT = join(ROOT, 'tests', 'fixtures', 'research-items-template.json');

async function getJson(path) {
  const res = await fetch(`${API}${path}`);
  if (!res.ok) throw new Error(`GET ${path} → ${res.status} ${res.statusText}`);
  return res.json();
}

/** Property id → {term, label}. The vocabulary is larger than one page. */
async function propertyIndex() {
  const index = new Map();
  for (let page = 1; page <= 20; page++) {
    const batch = await getJson(`/properties?per_page=200&page=${page}`);
    if (!batch.length) break;
    for (const p of batch) index.set(p['o:id'], { term: p['o:term'], label: p['o:label'] });
  }
  return index;
}

const index = await propertyIndex();
const template = await getJson(`/resource_templates/${TEMPLATE_ID}`);
const item = await getJson(`/items/${SAMPLE_ITEM_ID}`);

const properties = (template['o:resource_template_property'] ?? []).map((p) => {
  const id = p['o:property']['o:id'];
  const known = index.get(id);
  if (!known) {
    // Silently emitting `?id` here is how a map ends up with holes in it.
    throw new Error(`Property id ${id} is on the template but not in the vocabulary index`);
  }
  return { term: known.term, label: p['o:alternate_label'] || known.label };
});

const itemTerms = Object.keys(item).filter(
  (k) => k.includes(':') && !k.startsWith('o:') && !k.startsWith('@')
);

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  JSON.stringify(
    {
      _comment:
        'Generated by scripts/fetch-template-fixture.mjs from the live AMIRA API. Refresh when the template changes; do not hand-edit.',
      source: API,
      template: {
        id: TEMPLATE_ID,
        label: template['o:label'],
        propertyCount: properties.length,
        properties,
      },
      sampleItem: {
        id: SAMPLE_ITEM_ID,
        label: 'journal article with a DOI (the record AUDIT.md reviews)',
        terms: itemTerms,
      },
    },
    null,
    2
  ) + '\n'
);

console.log(
  `Fixture: ${properties.length} template properties, ${itemTerms.length} item terms → ${OUT.replace(ROOT, '.')}`
);
